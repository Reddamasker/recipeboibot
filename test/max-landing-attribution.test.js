  assert.equal(parseMaxLandingPayload('/start lc_site-landing_bad'),null);
  recordBotStart(user(504),'/start lc_arbitrary_'+token());
  assert.equal(db.prepare('SELECT campaign FROM acquisition_starts WHERE user_id=?').get(user(504).id).campaign,null);
  const reused=token();recordBotStart(user(505),'/start '+maxLandingPayload('ya-product-rsya-202611',reused));
