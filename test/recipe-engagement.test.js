test('HTTP GET and library preparation are not views; private POST acknowledges a delivered full recipe only', async () => {
  const u = user(), recipe = createRecipe(u.id, { ...dish, status: 'ready', nutrition: { calories: 1, protein: 0, fat: 0, carbs: 0, basis: 'serving', servings: 1, source: 'calculated' } });
  const params = new URLSearchParams({ auth_date: String(Math.floor(Date.now() / 1000)), user: JSON.stringify({ id: Number(u.telegram_id) }) });
  const check = [...params].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `${k}=${v}`).join('\n');
  const key = createHmac('sha256', 'WebAppData').update(process.env.TELEGRAM_BOT_TOKEN).digest();
  params.set('hash', createHmac('sha256', key).update(check).digest('hex'));
  const headers = { authorization: `tma ${params}`, 'content-type': 'application/json' };
  const server = createServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    const response = await fetch(base + '/api/recipes/' + recipe.id, { headers });
    assert.equal(response.status, 200); const full = await response.json();
    assert.ok(full.recipeViewToken); assert.equal(report(u).fullRecipeOpens, 0);
    const body = JSON.stringify({ token: full.recipeViewToken, eventId: randomUUID() });
    assert.equal((await fetch(base + '/api/engagement', { method: 'POST', body })).status, 401);
    assert.equal((await fetch(base + '/api/engagement', { method: 'POST', headers, body })).status, 200);
    assert.equal((await fetch(base + '/api/engagement', { method: 'POST', headers, body })).status, 200);
    assert.equal(report(u).fullRecipeOpens, 1);
  } finally { await new Promise(resolve => server.close(resolve)); }
});
